"""Print an introspection `__schema` as GraphQL SDL (schema.graphql)."""

INTROSPECTION_QUERY = """
query {
  __schema {
    queryType { name }
    types {
      kind name description
      fields { name description args { name description defaultValue type { ...T } } type { ...T } }
      inputFields { name description defaultValue type { ...T } }
      enumValues { name description }
    }
  }
}
fragment T on __Type { kind name ofType { kind name ofType { kind name ofType { kind name ofType { kind name } } } } }
"""


def type_str(t):
    if not t:
        return ''
    if t['kind'] == 'NON_NULL':
        return type_str(t['ofType']) + '!'
    if t['kind'] == 'LIST':
        return '[' + type_str(t['ofType']) + ']'
    return t['name']


def _doc(text, indent=''):
    if not text:
        return []
    text = str(text).strip().replace('"""', '\\"""')
    if '\n' not in text:
        return [f'{indent}"""{text}"""']
    return [f'{indent}"""', *[f'{indent}{line}' for line in text.split('\n')], f'{indent}"""']


def _args(args):
    if not args:
        return ''
    parts = []
    for a in args:
        default = f' = {a["defaultValue"]}' if a.get('defaultValue') is not None else ''
        parts.append(f'{a["name"]}: {type_str(a["type"])}{default}')
    return '(' + ', '.join(parts) + ')'


def schema_to_sdl(schema):
    root = (schema.get('queryType') or {}).get('name', 'Query')
    out = ['# Generated by scripts/export_schema.py from the live introspection. Do not edit by hand.', '']
    if root != 'Query':
        out += ['schema {', f'  query: {root}', '}', '']
    for t in sorted((t for t in schema['types'] if not t['name'].startswith('__')), key=lambda t: (t['name'] != root, t['name'])):
        kind, name = t['kind'], t['name']
        if kind == 'SCALAR':
            if name in ('String', 'Int', 'Float', 'Boolean', 'ID'):
                continue
            out += [*_doc(t.get('description')), f'scalar {name}', '']
        elif kind == 'ENUM':
            out += [*_doc(t.get('description')), f'enum {name} {{']
            for v in t.get('enumValues') or []:
                out += [*_doc(v.get('description'), '  '), f'  {v["name"]}']
            out += ['}', '']
        elif kind == 'INPUT_OBJECT':
            out += [*_doc(t.get('description')), f'input {name} {{']
            for f in t.get('inputFields') or []:
                default = f' = {f["defaultValue"]}' if f.get('defaultValue') is not None else ''
                out += [*_doc(f.get('description'), '  '), f'  {f["name"]}: {type_str(f["type"])}{default}']
            out += ['}', '']
        elif kind == 'OBJECT':
            out += [*_doc(t.get('description')), f'type {name} {{']
            for f in t.get('fields') or []:
                out += [*_doc(f.get('description'), '  '), f'  {f["name"]}{_args(f.get("args"))}: {type_str(f["type"])}']
            out += ['}', '']
    return '\n'.join(out).rstrip() + '\n'
