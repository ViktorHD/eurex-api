#!/usr/bin/env python3
"""Generate the machine-readable agent assets from the tool registry, ai.md and (if present) schema.graphql.

    python scripts/build_ai_assets.py           # write ai/*.json and llms-full.txt
    python scripts/build_ai_assets.py --check   # exit 1 when a committed file is out of date
"""
import argparse
import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, ROOT)

from eurex_mcp import definitions, tools  # noqa: E402

PLACEHOLDER_SERVER = 'https://YOUR-APP-HOST'


def read(name):
    path = os.path.join(ROOT, name)
    return open(path, encoding='utf-8').read() if os.path.isfile(path) else None


def tool_section():
    lines = ['## Tools (MCP server `python -m eurex_mcp.server`, REST `/api/v1/tools/<name>`)', '']
    for t in tools.TOOLS.values():
        args = ', '.join(f'{k}{"" if k in t.schema["required"] else "?"}: {v["type"]}' for k, v in t.schema['properties'].items())
        lines.append(f'- `{t.name}({args})`: {t.description}')
    return '\n'.join(lines)


def llms_full():
    schema = read('schema.graphql')
    parts = ['# Eurex Reference Data API: full context for AI agents', '',
             'One file: the instructions (ai.md), the tool list and the GraphQL schema. Generated by scripts/build_ai_assets.py.', '',
             read('ai.md').rstrip(), '', tool_section(), '', '## GraphQL schema (SDL)', '']
    if schema:
        parts += ['```graphql', schema.rstrip(), '```']
    else:
        parts += ['Not generated yet. Run scripts/export_schema.py with an API key, or use introspection (get_schema / section 4 above).']
    return '\n'.join(parts) + '\n'


def dumps(obj):
    return json.dumps(obj, indent=2, ensure_ascii=False) + '\n'


def outputs():
    return {
        'ai/claude_tools.json': dumps(definitions.claude_tools()),
        'ai/openai_tools.json': dumps(definitions.openai_tools()),
        'ai/openapi.json': dumps(definitions.openapi(PLACEHOLDER_SERVER)),
        'llms-full.txt': llms_full(),
    }


def main(argv=None):
    ap = argparse.ArgumentParser()
    ap.add_argument('--check', action='store_true')
    args = ap.parse_args(argv)
    stale = []
    for name, text in outputs().items():
        path = os.path.join(ROOT, name)
        if args.check:
            if read(name) != text:
                stale.append(name)
            continue
        os.makedirs(os.path.dirname(path), exist_ok=True)
        with open(path, 'w', encoding='utf-8') as f:
            f.write(text)
    if stale:
        print('Out of date: ' + ', '.join(stale) + '. Run python scripts/build_ai_assets.py', file=sys.stderr)
        return 1
    return 0


if __name__ == '__main__':
    sys.exit(main())
